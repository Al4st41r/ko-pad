"""Browser test for the single -/+ pair. Run: EP133_URL=<url> uv run --with playwright python tests/params_test.py"""
import os, sys
from playwright.sync_api import sync_playwright

URL = os.environ.get("EP133_URL") or sys.exit("Set EP133_URL")
fails = []
def check(name, ok, detail=""):
    print(("PASS " if ok else "FAIL ") + name + (f"  [{detail}]" if detail and not ok else ""))
    if not ok: fails.append(name)

with sync_playwright() as p:
    kw = {}
    if os.environ.get("CHROMIUM"): kw["executable_path"] = os.environ["CHROMIUM"]
    b = p.chromium.launch(**kw)
    pg = b.new_context(viewport={"width": 1194, "height": 834}).new_page()
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)[:120]))
    pg.goto(URL, wait_until="networkidle"); pg.evaluate("localStorage.clear()"); pg.reload(wait_until="networkidle")
    pg.click("#startBtn"); pg.wait_for_selector("#start.hide", state="attached", timeout=60000)
    t = lambda s: pg.inner_text(s).strip()
    check("starts on PATTERN 1", t("#pmPattern") == "PATTERN" and t("#pmVal") == "A01" and t("#lcdPat") == "A01")
    pg.click("#pmUp"); check("+ steps the pattern", t("#pmVal") == "A02" and t("#lcdPat") == "A02")
    pg.click("#pmDn"); pg.click("#pmDn"); check("- wraps the pattern to 99", t("#pmVal") == "A99")
    pg.click("#pmTiming"); check("TIMING goes to BPM first", t("#pmTiming") == "BPM" and t("#pmVal") == "120")
    pg.click("#pmUp"); check("+ raises the tempo", t("#bpmVal") == "121" and t("#pmVal") == "121")
    pg.click("#pmTiming"); check("TIMING again goes to BARS", t("#pmTiming") == "BARS")
    pg.click("#pmTiming"); pg.click("#pmTiming"); check("then OCTAVE", t("#pmTiming") == "OCTAVE")
    pg.click("#pmDn"); check("- lowers the octave", t("#pmVal") == "-1")
    pg.click("#pmTiming"); check("TIMING wraps to BPM", t("#pmTiming") == "BPM")
    pg.click("#pmPattern"); check("PATTERN selects the pattern again", t("#pmVal") == "A99")
    LABELS = ["7", "8", "9", "4", "5", "6", "1", "2", "3", ".", "0", "ENT"]  # the pad layout, as on the device
    pad = lambda k: pg.click(f'#pads .pad[data-i="{LABELS.index(k)}"]')
    snd = lambda: pg.evaluate("A.pad(A.keys ? A.keysPad : A.sel).s")
    pg.click("#pmSound")
    has_sounds = pg.evaluate("fetch('samples/catalogue.json').then((r) => r.ok).catch(() => false)")  # the factory catalogue is optional
    check("factory sounds are installed on the server", has_sounds)
    ids = pg.evaluate("[...A.catalogue.map((c) => c.id), ...[]].sort((a, b) => a - b)")
    nxt = lambda n, k=1: ids[(ids.index(n) + k) % len(ids)]
    pad("7"); s0 = snd(); pg.click("#pmUp")
    check("SOUND: pad 7 + gives the next sound", snd() == nxt(s0) and t("#pmVal").startswith(f"{snd()} "), f"{s0} -> {snd()} {t('#pmVal')}")
    pg.click("#pmDn"); check("- goes back", snd() == s0, str(snd()))
    pg.keyboard.down("Shift"); pg.click("#pmUp"); pg.keyboard.up("Shift")
    check("SHIFT + steps ten sounds", snd() == nxt(s0, 10), f"{s0} -> {snd()}")
    pg.click("#pmSound")
    check("tapping SOUND again starts number entry", pg.evaluate("A.soundLatch") is True and t("#pmVal") == "_", t("#pmVal"))
    pad("1"); pad("2"); check("typing shows the digits", t("#pmVal") == "12_", t("#pmVal"))
    pad("."); check(". deletes a digit", t("#pmVal") == "1_", t("#pmVal"))
    pad("2"); pad("ENT"); check("ENT sets the typed sound on the pad", snd() == 12 and pg.evaluate("A.soundLatch") is False, str(snd()))
    pg.click("#pmSound"); pad("0"); pad("ENT"); check("typing 0 empties the pad", snd() == 0, str(snd()))
    pg.click("#pmSound"); pad("9"); pad("9"); pad("9"); pad("ENT")
    check("a sound that does not exist leaves the pad alone", snd() == 0, str(snd()))
    big = next(n for n in ids if n >= 100)  # a three-digit sound that exists
    pg.dispatch_event("#pmSound", "pointerdown")
    for d in str(big): pad(d)
    check("holding SOUND and typing shows the digits", t("#pmVal") == f"{big}_", t("#pmVal"))
    pg.dispatch_event("#pmSound", "pointerup")
    check("releasing SOUND sets the typed sound", snd() == big and pg.evaluate("A.soundLatch") is False, str(snd()))
    pg.click("#pmUp"); first = snd()
    pg.click("#tabs >> text=SOUND"); check("SOUND tab lists sounds", "No sounds yet" not in pg.inner_text("#panel"), "")
    pg.click("#sn"); check("SOUND tab NEXT steps the pad's sound", snd() == nxt(first), f"{first} -> {snd()}")
    pg.click("#sp"); check("SOUND tab PREVIOUS steps back", snd() == first, str(snd()))
    pg.click("#tabs >> text=PADS")
    pg.evaluate("A.project.groups[0].patterns={'1':{bars:1,beats:4,ev:[{t:48,p:2,v:100,d:24},{t:48,p:5,v:100,d:24},{t:96,p:0,v:100,d:24}]}}; A.project.groups[0].cur=1; A.g=0; A.refresh()")
    pg.click("#pmStep"); pg.wait_for_timeout(100)
    hits = lambda: pg.evaluate("[...document.querySelectorAll('#pads .pad')].map((e, i) => e.lastElementChild.classList.contains('hit') ? i : -1).filter((i) => i >= 0)")
    check("STEP at 1.1.1: no pad has a hit", hits() == [], str(hits()))
    pg.click("#pmUp"); pg.click("#pmUp"); pg.wait_for_timeout(100)
    check("stepping to 1.1.3 lights the dots of the pads with a hit there", hits() == [2, 5], str(hits()))
    pg.click("#pmUp"); pg.wait_for_timeout(100); check("the dots move on with the cursor", hits() == [], str(hits()))
    pg.click("#pmUp"); pg.wait_for_timeout(100); check("the next hit lights its pad", hits() == [0], str(hits()))
    for _ in range(4): pg.click("#pmDn")
    pg.wait_for_timeout(100)
    check("back at the start there are no dots", hits() == [], str(hits()))
    pg.click("#pmStep")
    pg.click("#pmStep"); check("STEP starts at 1.1.1", t("#pmVal") == "1.1.1", t("#pmVal"))
    pg.click("#pmUp"); check("+ moves the step cursor", t("#pmVal") == "1.1.2", t("#pmVal"))
    pg.click("#pmDn"); pg.click("#pmDn"); check("- wraps to the last step", t("#pmVal") == "1.4.4", t("#pmVal"))
    pg.click("#bpmVal"); check("tapping the tempo selects BPM", t("#pmTiming") == "BPM")
    check("no page errors", not errs, str(errs))
    b.close()
sys.exit(1 if fails else 0)
